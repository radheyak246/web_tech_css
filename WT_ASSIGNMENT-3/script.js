function normalizeName(name)
{
    return name
    .toLowerCase()
    .replace(/[\s.]/g,"");
}

/* =========================================================
   SEARCH FUNCTION
   ========================================================= */

function searchFaculty() {

    const searchText = normalizeName(searchInput.value);


    /* Empty search */

    if (searchText === "") {

        profileContainer.innerHTML = `

            <div class="no-result">

                <h2>Search for a Faculty Member</h2>

                <p>
                    Enter a faculty name in the search box
                    to view the profile.
                </p>

            </div>

        `;

        return;
    }


    /* Search faculty */

    const result = faculty.find(person =>
        normalizeName(person.name).includes(searchText)
    );


    /* If faculty found */

    if (result) {

        displayFaculty(result);

    }


    /* If faculty not found */

    else {

        profileContainer.innerHTML = `

            <div class="no-result">

                <h2>Faculty Not Found</h2>

                <p>
                    No faculty member matches
                    "${searchInput.value}".
                </p>

            </div>

        `;
    }
}


/* =========================================================
   SEARCH BUTTON EVENT
   ========================================================= */

searchButton.addEventListener(
    "click",
    searchFaculty
);


/* =========================================================
   ENTER KEY EVENT
   ========================================================= */

searchInput.addEventListener(
    "keyup",
    function(event) {

        if (event.key === "Enter") {

            searchFaculty();

        }
    }
);